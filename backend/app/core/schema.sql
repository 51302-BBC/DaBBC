CREATE TABLE IF NOT EXISTS employees (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(name) > 0),
    email text NOT NULL UNIQUE,
    password_hash text,
    roles text[] NOT NULL DEFAULT ARRAY['employee'],
    supervisor_id bigint REFERENCES employees(id),
    active boolean NOT NULL DEFAULT true,
    started_on date,
    phone text,
    address text,
    emergency_contact text,
    CHECK (id <> supervisor_id)
);
ALTER TABLE employees ADD COLUMN IF NOT EXISTS inactive_on date;
UPDATE employees AS employee
SET roles = COALESCE(
    (SELECT array_agg(DISTINCT CASE WHEN role = 'reception' THEN 'admin' ELSE role END)
     FROM unnest(employee.roles) AS role WHERE role <> 'co_manager'),
    ARRAY['employee']
)
WHERE roles && ARRAY['reception','co_manager'];
CREATE INDEX IF NOT EXISTS employees_supervisor_idx ON employees(supervisor_id);

CREATE TABLE IF NOT EXISTS sessions (
    digest text PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES employees(id),
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_emp_idx ON sessions(employee_id);

CREATE TABLE IF NOT EXISTS account_tokens (
    digest text PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES employees(id),
    purpose text NOT NULL CHECK (purpose IN ('activate', 'reset')),
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS account_tokens_emp_idx ON account_tokens(employee_id, purpose);

CREATE TABLE IF NOT EXISTS clients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(name) > 0),
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS client_assignees (
    client_id bigint NOT NULL REFERENCES clients(id),
    employee_id bigint NOT NULL REFERENCES employees(id),
    PRIMARY KEY (client_id, employee_id)
);
CREATE INDEX IF NOT EXISTS client_assignees_employee_idx ON client_assignees(employee_id);

CREATE TABLE IF NOT EXISTS tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL CHECK (length(title) > 0),
    description text NOT NULL DEFAULT '',
    client_id bigint NOT NULL REFERENCES clients(id),
    assignee_id bigint NOT NULL REFERENCES employees(id),
    created_by bigint NOT NULL REFERENCES employees(id),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'in_progress', 'completed', 'canceled')),
    due_on date,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tasks_assignee_idx ON tasks(assignee_id);

CREATE TABLE IF NOT EXISTS task_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks(id),
    actor_id bigint NOT NULL REFERENCES employees(id),
    action text NOT NULL,
    changes jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS task_history_task_idx ON task_history(task_id);

CREATE TABLE IF NOT EXISTS notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES employees(id),
    message text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at timestamptz
);
CREATE INDEX IF NOT EXISTS notifications_employee_idx ON notifications(employee_id, id DESC);
